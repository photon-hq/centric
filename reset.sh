#!/usr/bin/env bash
set -euo pipefail

# reset.sh
# Safely reset embeddings, scraped documents, and scraper config so you can start fresh.
# Usage:
#   ./reset.sh          # interactive (asks for confirmation)
#   ./reset.sh --yes    # force reset without prompting

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
EMBEDDINGS_DIR="$ROOT_DIR/embeddings"
DOCUMENTS_DIR="$ROOT_DIR/documents"
SCRAPER_CONFIG="$ROOT_DIR/config/scraper.config.json"
BACKUP_DIR="$ROOT_DIR/.reset-backups"
FORCE=false

for arg in "$@"; do
  case "$arg" in
    --yes|-y)
      FORCE=true
      ;;
    --help|-h)
      sed -n '1,120p' "$0"
      exit 0
      ;;
  esac
done

echo "This script will remove cached embeddings, all scraped documents (files prefixed with 'scraped_'), and reset the scraper config to the default state."
if [ "$FORCE" = false ]; then
  read -p "Proceed? (y/N): " confirm
  case "$confirm" in
    [yY]|[yY][eE][sS]) ;;
    *) echo "Aborted."; exit 0 ;;
  esac
fi

mkdir -p "$BACKUP_DIR"
TIMESTAMP=$(date -u +%Y%m%dT%H%M%SZ)

# Backup and clear embeddings
if [ -d "$EMBEDDINGS_DIR" ]; then
  echo "Backing up embeddings to $BACKUP_DIR/embeddings-backup-$TIMESTAMP.tar.gz"
  tar -czf "$BACKUP_DIR/embeddings-backup-$TIMESTAMP.tar.gz" -C "$ROOT_DIR" "embeddings" || true
  echo "Removing embeddings directory: $EMBEDDINGS_DIR"
  rm -rf "$EMBEDDINGS_DIR"
else
  echo "No embeddings directory found (skipping)"
fi

# Recreate empty embeddings dir
mkdir -p "$EMBEDDINGS_DIR"

# Remove scraped documents only (preserve manual docs)
if [ -d "$DOCUMENTS_DIR" ]; then
  echo "Removing scraped documents from $DOCUMENTS_DIR"
  shopt -s nullglob
  SCRAPED_FILES=("$DOCUMENTS_DIR"/scraped_*)
  if [ ${#SCRAPED_FILES[@]} -gt 0 ]; then
    echo "Backing up scraped documents to $BACKUP_DIR/scraped-docs-backup-$TIMESTAMP.tar.gz"
    tar -czf "$BACKUP_DIR/scraped-docs-backup-$TIMESTAMP.tar.gz" -C "$DOCUMENTS_DIR" -- "${SCRAPED_FILES[@]##$DOCUMENTS_DIR/}" || true
    rm -f "$DOCUMENTS_DIR"/scraped_*
    echo "Removed ${#SCRAPED_FILES[@]} scraped file(s)."
  else
    echo "No scraped_ files found in $DOCUMENTS_DIR"
  fi
  shopt -u nullglob
else
  echo "No documents directory found (skipping)"
fi

# Backup and reset scraper config
if [ -f "$SCRAPER_CONFIG" ]; then
  echo "Backing up current scraper config to $BACKUP_DIR/scraper.config.json.backup.$TIMESTAMP"
  cp "$SCRAPER_CONFIG" "$BACKUP_DIR/scraper.config.json.backup.$TIMESTAMP"
else
  echo "No existing scraper config to backup"
fi

# Write default config (self-documenting JSON template)
cat > "$SCRAPER_CONFIG" <<'JSON'
{
  "/**": "============================================",
  "/** NOTICE": "This file is AUTO-GENERATED by the Knowledge Base Configuration Dashboard",
  "/** Location": "http://localhost:3000/config (when dashboard is running)",
  "/** Purpose": "Stores website scraping configuration for automatic knowledge base generation",
  "/**": "============================================",
  "/**": "",
  "/** CONFIGURATION": {
    "websiteUrl": "The main URL of your website to scrape",
    "includeSameOriginSubdomains": "Set to true to also scrape subdomains (e.g., docs.example.com)",
    "maxDepth": "How many link levels deep to crawl (recommended: 2-5)"
  },
  "/**": "",
  "/** USAGE": [
    "1. Start the dashboard: cd dashboard && ./start.sh",
    "2. Open http://localhost:3000/config",
    "3. Enter your website URL",
    "4. Configure options and click 'Start Scraping'",
    "5. Scraped content is saved to documents/ folder with 'scraped_' prefix",
    "6. The AI agent will automatically use these documents"
  ],
  "/**": "",
  "/** NOTES": {
    "rate_limiting": "The scraper waits 500ms between requests to be respectful",
    "file_naming": "Scraped files are prefixed with 'scraped_' for easy identification",
    "clearing": "Use 'Clear All Scraped Documents' button to remove scraped content",
    "manual_docs": "Manual documents (without 'scraped_' prefix) are preserved when clearing"
  },
  "/**": "",
  "/**": "============================================",
  "/**": "ACTUAL CONFIGURATION (edit via dashboard, not manually)",
  "/**": "============================================",
  "websiteUrl": "",
  "includeSameOriginSubdomains": true,
  "maxDepth": 3
}
JSON

echo "Reset complete. Backups saved to: $BACKUP_DIR"

echo "Summary:"
echo " - Embeddings directory cleared and recreated: $EMBEDDINGS_DIR"
echo " - Scraped documents removed from: $DOCUMENTS_DIR (only files named scraped_*)"
echo " - Scraper config reset to default: $SCRAPER_CONFIG"

echo "You can now re-run the dashboard and start a fresh scrape."

exit 0
